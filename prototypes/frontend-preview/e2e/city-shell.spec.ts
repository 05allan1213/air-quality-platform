import { test, expect, ready, cityState, noOverflow } from './fixtures'

test('城市数据身份、收藏、趋势表与同窗历史操作', async ({page}) => {
  await page.goto('/city'); await ready(page,'云汀市')
  await expect(page.locator('.aqi-value > strong')).toHaveText('42')
  await page.getByRole('button',{ name:'收藏城市' }).click()
  await expect(page.getByRole('button',{name:'已收藏'})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'查看观测明细'}).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('tbody tr')).toHaveCount(7)
  await expect(dialog.getByRole('row').filter({has:page.getByRole('cell',{name:'CO',exact:true})})).toContainText('0.59 mg/m³')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'12 小时'}).click()
  await expect(page.locator('.plot-footer')).toContainText('12 / 12')
  await page.getByRole('button',{name:'趋势数据表'}).click()
  await expect(dialog.locator('tbody tr')).toHaveCount(12)
  await expect(dialog.locator('tbody tr').last()).toContainText('41')
  await page.getByRole('button',{name:'关闭数据表'}).click()
  await page.getByRole('button',{name:'查询历史'}).click()
  await expect(page.locator('.query-summary')).toContainText('24 条')
  await expect(page.locator('#city-ledger tbody tr').first()).toContainText('00:00')
  await page.getByRole('button',{name:'历史下一页'}).click(); await expect(page.locator('#city-ledger tbody tr').first()).toContainText('06:00')
  await page.getByLabel('观测日期').selectOption('2024-05-17'); await page.getByRole('button',{name:'查询历史'}).click()
  await expect(page.locator('.query-summary')).toContainText('指定窗口无记录'); await expect(page.locator('#city-ledger tbody tr')).toHaveCount(0)
  await page.getByRole('button',{name:'同城站点',exact:true}).click()
  await page.getByRole('button',{name:'查看江湾站站址摘要'}).click(); await expect(dialog).toContainText('F-S01');await expect(dialog).toContainText('201')
  await page.getByRole('button',{name:'关闭摘要'}).click()
  await page.getByRole('link',{name:'进入对比'}).click(); await ready(page,'分析工作台')
  await expect(page).toHaveURL(/analysis\?from=city/); await expect(page.locator('.series-legend')).toContainText('云汀市'); await expect(page.locator('.series-legend')).toContainText('雾川市')
})

